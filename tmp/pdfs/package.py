from pathlib import Path
import json,csv
out=Path('output/question-banks')
report=json.loads((out/'extraction-report.json').read_text(encoding='utf-8'))
priority=[
 ('2c2',8,'原稿 pinch 和 unusual 都拼写正确，属于多答案题；当前暂选 C。'),
 ('me1',11,'原稿有两个词与本练习词表匹配，需确认是否存在两个正确拼写。'),
 ('4c1',7,'fathomless 的 B（very deep）和 C（cannot be measured）均有合理性；答案表为 C。'),
 ('6b11',1,'coon 的选项没有明确正确释义；原稿可能有词汇或选项错误。'),
 ('ma8',7,'gnarled 与选项释义不符，原稿可能想写 snarled。'),
 ('mc2',9,'gnarled 与选项释义不符，原稿可能想写 snarled。'),
 ('6a7',1,'calcimine 的选项 wall cleaner 不准确；应复核原稿。'),
 ('6b12',5,'indomitable 的选项 not able to be trained 不准确；需复核原稿。')]
rows=[]
for f in sorted(out.glob('reading-vocabulary-*.json')):
 if '.draft' in f.name:continue
 for w in json.loads(f.read_text(encoding='utf-8'))['worksheets']:
  for n,q in enumerate(w['questions'],1):
   notes=[note for code,i,note in priority if code==w['code'] and i==n]
   rows.append([w['code'],w['title_en'],n,q['prompt'],*q['choices'],chr(65+q['correct_index']),q['choices'][q['correct_index']],'需复核','；'.join(notes)])
with (out/'answer-review.csv').open('w',encoding='utf-8-sig',newline='') as f:
 writer=csv.writer(f);writer.writerow(['练习编号','练习名称','题号','题目','A','B','C','D','暂定答案','暂定答案内容','状态','重点问题']);writer.writerows(rows)
